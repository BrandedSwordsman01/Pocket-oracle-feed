"""Export frozen AEGIS parameters from research/aegis_results.json to web/js/aegis_params.js for the app."""
import json, os
here = os.path.dirname(__file__)
R = json.load(open(os.path.join(here, "aegis_results.json")))
g = R["vol_models"]["garch"]
theta = R.get("trading_15m", {}).get("G AEGIS ⊕ market, conservative bound", {}).get("theta", 0.02)
P = dict(garch=dict(w=g["w"], a=g["a"], b=g["b"], nu=g["nu"]), diurnal=R["vol_models"]["diurnal"],
         platt=R["platt"]["E"], draws=R["platt_E_draws"], omega=R["omega"], theta=max(theta, 0.02),
         source="research/run_aegis.py (frozen; fit before 2026-10-23, calibrated on train)")
js = ("/* Generated by research/export_app_params.py - do not edit. */\n(function (root) {\n  var P = " + json.dumps(P) +
      ";\n  if (typeof module !== 'undefined' && module.exports) module.exports = P; else root.AEGIS_PARAMS = P;\n})(this);\n")
open(os.path.join(here, "..", "web", "js", "aegis_params.js"), "w").write(js)
print("wrote web/js/aegis_params.js; omega", P["omega"], "theta", P["theta"])
