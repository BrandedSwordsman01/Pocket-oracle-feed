"""Full KXBTC15M strategy study. Writes docs/backtest_results_15m.md and research/results_15m.json.

Protocol
  - days split chronologically: train 50% / validation 25% / test 25% (test touched once, at the end)
  - each family's parameter grid is evaluated on TRAIN; the config with the best train t-stat (min 40 trades) is chosen
  - the chosen config is confirmed on VALIDATION; only then reported on TEST
  - robustness: share of grid configs with positive expectancy on train AND validation
  - walk-forward: rolling 14-day train / 7-day test folds for the fitted models (ensemble, blend)
Usage: python3 run_15m_study.py DATA_DIR [OUT_MD]
"""
import itertools, json, math, os, sys, time, collections
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from kbt import data as D, strategies as S, backtest as B, models as M

data_dir = sys.argv[1]
out_md = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "docs", "backtest_results_15m.md")
t0 = time.time()
ds = D.load(data_dir)
tr_days, va_days, te_days = B.split_days(ds.days)
def part(days): return {k: w for k, w in ds.windows.items() if D.utc_day(w[0]["close"]) in days}
W_tr, W_va, W_te = part(tr_days), part(va_days), part(te_days)
rows_of = lambda W: [r for w in W.values() for r in w]
R_tr, R_va, R_te = rows_of(W_tr), rows_of(W_va), rows_of(W_te)
fmt_d = lambda ds_: f"{min(ds_)} .. {max(ds_)}"
out = collections.OrderedDict()
lines = []
P = lines.append
P("# KXBTC15M strategy study\n")
P(f"Generated by `research/run_15m_study.py` in {{elapsed}}s. Data: {ds.meta['n_markets']} settled 15-minute windows, "
  f"{len(ds.rows)} minute-level decision rows (14 to 1 min before close), {ds.days[0]} .. {ds.days[-1]}. "
  f"Bitstamp: {'yes' if ds.meta['has_bitstamp'] else 'no'}; Deribit DVOL: {'yes' if ds.meta['has_dvol'] else 'no'}.\n")
P(f"- **Train** {fmt_d(tr_days)} ({len(W_tr)} windows) · **Validation** {fmt_d(va_days)} ({len(W_va)}) · **Test** {fmt_d(te_days)} ({len(W_te)}), touched once.")
P("- Execution: buy at the ask / sell at the bid, Kalshi taker fee on every order, 10 contracts per trade, stale quotes (>180s) never traded, max spread 5¢ unless stated.")
P("- Per-contract P&L is in cents after fees. t = mean / standard error. A result counts as real only if it holds on validation **and** test with t > 2.\n")

# ------------------------------------------------------------------ benchmark basis (Strategy B prerequisite)
P("## 1. Settlement benchmark vs spot (is the 'lag' real?)\n")
basis = np.array([w[0]["basis"] for w in ds.windows.values() if w[0]["basis"] == w[0]["basis"]]) * 1e4
P(f"Each window's strike is the BRTI 60-second average at the open. Compared with the Coinbase close of the same minute: "
  f"mean basis **{basis.mean():+.2f} bp**, std **{basis.std():.2f} bp**, 95% of windows within ±{np.percentile(np.abs(basis), 95):.1f} bp (n={len(basis)}).")
if ds.meta["has_bitstamp"]:
    diffs = np.array([(r["S_bs"] / r["S"] - 1) * 1e4 for r in ds.rows if r["S_bs"] == r["S_bs"]])
    P(f"Bitstamp vs Coinbase at decision times: mean {diffs.mean():+.2f} bp, std {diffs.std():.2f} bp.")
sig_med = np.median([r["sigma"] for r in ds.rows]) * 1e4
P(f"For scale: median 1-minute BTC volatility is {sig_med:.1f} bp, so a {basis.std():.1f} bp basis error is about "
  f"{basis.std()/sig_med:.1f} minutes of noise. Strategy B is tested both with and without the basis correction.\n")
out["basis_bp"] = dict(mean=float(basis.mean()), std=float(basis.std()))

# ------------------------------------------------------------------ helper
def evaluate(strat, W, costs=None):
    return B.metrics(B.run(W, strat, costs or B.Costs()))

def row_md(name, m):
    if not m or m.get("n", 0) == 0:
        return f"| {name} | 0 | | | | | | | |"
    pf = "∞" if m["profit_factor"] == float("inf") else f"{m['profit_factor']:.2f}"
    return (f"| {name} | {m['n']} | {m['per_contract_c']:+.2f} | {m['t']:+.2f} | {m['win_rate']:.0%} | {pf} | "
            f"${m['net']:+.2f} | ${m['max_dd']:.2f} | {m['green_days']} |")

HDR = "| Strategy | Trades | ¢/contract | t | Win | PF | Net (10 lots) | Max DD | Green days |\n|---|---|---|---|---|---|---|---|---|"

def grid(cls, space, base=None):
    keys = list(space)
    for combo in itertools.product(*[space[k] for k in keys]):
        p = dict(zip(keys, combo))
        if "window" in p:
            p["min_left"], p["max_left"] = p.pop("window")
        yield (cls(**p) if base is None else cls(base, **p))

def select(family, strategies, min_trades=40):
    """Evaluate every config on train and validation; choose by train t-stat; report robustness."""
    res = []
    for s in strategies:
        s.fit(R_tr)
        mt = evaluate(s, W_tr)
        mv = evaluate(s, W_va)
        res.append((s, mt, mv))
    ok = [x for x in res if x[1].get("n", 0) >= min_trades]
    pos_tr = sum(1 for x in res if x[1].get("n", 0) >= min_trades and x[1]["per_contract_c"] > 0)
    pos_both = sum(1 for x in ok if x[1]["per_contract_c"] > 0 and x[2].get("n", 0) > 0 and x[2]["per_contract_c"] > 0)
    best = max(ok, key=lambda x: x[1]["t"]) if ok else None
    return dict(family=family, n_configs=len(res), n_eligible=len(ok), pos_train=pos_tr, pos_both=pos_both, best=best, all=res)

families = collections.OrderedDict()
print("A ...", file=sys.stderr)
families["A RSI momentum"] = select("A", grid(S.RSIMomentum, dict(
    hi=[55, 60, 65, 70], confirm5=[True, False], window=[(3, 10), (2, 6), (6, 12)], use_exit=[True, False], max_price=[0.8, 0.95])))
for s in families["A RSI momentum"]["all"]:
    pass
print("B ...", file=sys.stderr)
families["B Momentum / lag"] = select("B", grid(S.MomentumLag, dict(
    z=[1.0, 1.5, 2.0, 2.5], lag_frac=[0.3, 0.5, 0.8], benchmark_adjust=[True, False], use_exit=[True, False])))
print("C ...", file=sys.stderr)
vol_srcs = ["realized", "implied", "mix"] if ds.meta["has_dvol"] else ["realized"]
families["C Fair value"] = select("C", grid(S.FairValue, dict(
    edge=[0.02, 0.04, 0.06, 0.10], vol=vol_srcs, vol_mult=[0.8, 1.0, 1.2], dist=["normal", "t4"], window=[(2, 6), (6, 14), (2, 14)])))
bestC = families["C Fair value"]["best"][0] if families["C Fair value"]["best"] else S.FairValue()
bestA = families["A RSI momentum"]["best"][0] if families["A RSI momentum"]["best"] else S.RSIMomentum()
print("D ...", file=sys.stderr)
dlist = [S.FlipGuard(S.FairValue(**bestC.p), flip_exit=fx) for fx in (0.4, 0.5, 0.6)]
dlist += [S.FlipGuard(S.RSIMomentum(**bestA.p), flip_exit=fx) for fx in (0.4, 0.5, 0.6)]
dlist += [S.FairValue(**dict(bestC.p, flip_max=fm)) for fm in (0.15, 0.25, 0.35)]
families["D Flip-risk filter/exit"] = select("D", dlist, min_trades=20)
print("E ...", file=sys.stderr)
families["E Ensemble"] = select("E", [S.Ensemble(edge=e) for e in (0.02, 0.03, 0.05, 0.08)])
families["Baseline: blend (app v0.5)"] = select("blend", [S.Blend(edge=e) for e in (0.02, 0.04)])
families["Baseline: leading side"] = select("lead", [S.LeadingSide(at_min=m) for m in (10, 5, 3, 2)])

# ------------------------------------------------------------------ results table
P("## 2. Strategy comparison\n")
P("Each family's best configuration was chosen on **train**, then checked on **validation**. The test column is the single, final look.\n")
P("| Family | Configs | Positive on train | Positive on train **and** validation | Selected config |\n|---|---|---|---|---|")
for name, f in families.items():
    lab = f["best"][0].label() if f["best"] else "—"
    P(f"| {name} | {f['n_configs']} | {f['pos_train']}/{f['n_eligible']} | {f['pos_both']}/{f['n_eligible']} | `{lab}` |")
P("")
P("### Train / validation / test for the selected configs\n")
P(HDR)
final = collections.OrderedDict()
for name, f in families.items():
    if not f["best"]:
        P(f"| {name} | – | | | | | | | |"); continue
    s, mt, mv = f["best"]
    mte = evaluate(s, W_te)
    final[name] = (s, mt, mv, mte)
    P(row_md(f"{name} · train", mt)); P(row_md(f"{name} · validation", mv)); P(row_md(f"**{name} · TEST**", mte))
P("")
out["families"] = {n: dict(config=v[0].label(), train=v[1], val=v[2], test=v[3]) for n, v in final.items()}

# ------------------------------------------------------------------ sensitivity (Reddit's claim: '100 variants all profitable')
P("## 3. Parameter sensitivity\n")
fa = families["A RSI momentum"]
pcs = sorted([x[1]["per_contract_c"] for x in fa["all"] if x[1].get("n", 0) >= 40])
pcv = sorted([x[2]["per_contract_c"] for x in fa["all"] if x[2].get("n", 0) >= 20])
if pcs:
    P(f"**A (RSI), {fa['n_configs']} variants:** train ¢/contract ranges from {pcs[0]:+.2f} to {pcs[-1]:+.2f} (median {np.median(pcs):+.2f}); "
      f"validation median {np.median(pcv):+.2f}. Variants positive on train: {fa['pos_train']}/{fa['n_eligible']}. "
      "The report that 100/100 variants were profitable is not reproduced once you pay executable prices and fees.\n")
fc = families["C Fair value"]
P("**C (fair value) by edge threshold**, median train ¢/contract across the other parameters:\n")
P("| Edge ≥ | Median train ¢ | Median validation ¢ | Configs |\n|---|---|---|---|")
for e in (0.02, 0.04, 0.06, 0.10):
    xs = [x for x in fc["all"] if x[0].p["edge"] == e and x[1].get("n", 0) >= 20]
    if xs:
        P(f"| {e:.2f} | {np.median([x[1]['per_contract_c'] for x in xs]):+.2f} | "
          f"{np.median([x[2]['per_contract_c'] for x in xs if x[2].get('n', 0)] or [float('nan')]):+.2f} | {len(xs)} |")
if ds.meta["has_dvol"]:
    P("\n**C by volatility source** (median validation ¢/contract): " + ", ".join(
        f"{v}: {np.median([x[2]['per_contract_c'] for x in fc['all'] if x[0].p['vol'] == v and x[2].get('n', 0)] or [float('nan')]):+.2f}"
        for v in vol_srcs))
P("")

# ------------------------------------------------------------------ probability quality
P("## 4. Probability quality (Brier, tradeable rows with mid 5–95¢)\n")
P("| Model | Split | n | Brier model | Brier market | Log loss model | Log loss market |\n|---|---|---|---|---|---|---|")
prob_models = [("C fair value (selected)", bestC), ("E ensemble", families["E Ensemble"]["best"][0] if families["E Ensemble"]["best"] else None),
               ("Blend", families["Baseline: blend (app v0.5)"]["best"][0] if families["Baseline: blend (app v0.5)"]["best"] else None)]
for nm, s in prob_models:
    if s is None:
        continue
    for split, R in (("validation", R_va), ("test", R_te)):
        b = B.brier_report(R, s.prob)
        P(f"| {nm} | {split} | {b['n']} | {b['brier_model']:.4f} | {b['brier_market']:.4f} | {b['ll_model']:.4f} | {b['ll_market']:.4f} |")
P("\nCalibration of the selected fair-value model on test (predicted vs realised YES rate):\n")
P("| Bin | n | Mean predicted | Realised |\n|---|---|---|---|")
for lo, hi, n, mp, yr in B.calibration_table(R_te, bestC.prob):
    P(f"| {lo:.1f}–{hi:.1f} | {n} | {mp:.3f} | {yr:.3f} |")
P("")

# ------------------------------------------------------------------ ensemble weights + ablation
P("## 5. Ensemble: weights and ablations (validation)\n")
E = S.Ensemble(edge=families["E Ensemble"]["best"][0].p["edge"] if families["E Ensemble"]["best"] else 0.03).fit(R_tr)
P("Standardised logistic weights (fit on train): " + ", ".join(f"`{n}` {w:+.3f}" for n, w in zip(E.names, E.w)) + "\n")
P("| Ablation | Validation log loss | Δ vs full | Validation ¢/contract | Trades |\n|---|---|---|---|---|")
full_ll = B.brier_report(R_va, E.prob)["ll_model"]
mv = evaluate(E, W_va)
P(f"| full | {full_ll:.5f} | – | {mv.get('per_contract_c', float('nan')):+.2f} | {mv.get('n', 0)} |")
for drop in [f for f in S.FEATURES if f != "logit_mid"]:
    feats = [f for f in S.FEATURES if f != drop]
    e = S.Ensemble(edge=E.p["edge"], features=feats).fit(R_tr)
    ll = B.brier_report(R_va, e.prob)["ll_model"]
    m = evaluate(e, W_va)
    P(f"| − {drop} | {ll:.5f} | {ll - full_ll:+.5f} | {m.get('per_contract_c', float('nan')):+.2f} | {m.get('n', 0)} |")
P("\nA positive Δ means the feature helped (removing it made validation log loss worse).\n")

# ------------------------------------------------------------------ walk-forward
P("## 6. Walk-forward (rolling 14-day train → 7-day test, models refit each fold)\n")
P("| Fold test period | Blend ¢ (n) | Ensemble ¢ (n) | Fair value ¢ (n) |\n|---|---|---|---|")
wf = collections.defaultdict(list)
days = ds.days
i = 14
while i + 7 <= len(days):
    trd, ted = set(days[i - 14:i]), set(days[i:i + 7])
    Wtr = {k: w for k, w in ds.windows.items() if D.utc_day(w[0]["close"]) in trd}
    Wte = {k: w for k, w in ds.windows.items() if D.utc_day(w[0]["close"]) in ted}
    Rtr = rows_of(Wtr)
    bl = S.Blend(edge=0.02).fit(Rtr); en = S.Ensemble(edge=E.p["edge"]).fit(Rtr); fv = S.FairValue(**bestC.p)
    cells = []
    for nm, s in (("blend", bl), ("ens", en), ("fv", fv)):
        tr_ = B.run(Wte, s, B.Costs()); wf[nm] += tr_
        m = B.metrics(tr_)
        cells.append(f"{m.get('per_contract_c', float('nan')):+.2f} ({m.get('n', 0)})")
    P(f"| {min(ted)} .. {max(ted)} | " + " | ".join(cells) + " |")
    i += 7
P("| **All folds** | " + " | ".join(f"{B.metrics(wf[k]).get('per_contract_c', float('nan')):+.2f} ({B.metrics(wf[k]).get('n', 0)}), t={B.metrics(wf[k]).get('t', float('nan')):+.2f}" for k in ("blend", "ens", "fv")) + " |\n")
out["walk_forward"] = {k: B.metrics(v) for k, v in wf.items()}

# ------------------------------------------------------------------ cost stress + regimes on test
P("## 7. Cost stress and regimes (TEST, selected configs)\n")
P("| Strategy | no slippage | +1¢ slippage | +2¢ slippage | 70% fill rate |\n|---|---|---|---|---|")
for name, (s, *_r) in final.items():
    cells = []
    for c in (B.Costs(), B.Costs(slippage=0.01), B.Costs(slippage=0.02), B.Costs(fill_prob=0.7)):
        m = evaluate(s, W_te, c)
        cells.append(f"{m.get('per_contract_c', float('nan')):+.2f} ({m.get('n', 0)})")
    P(f"| {name} | " + " | ".join(cells) + " |")
P("")
sig_tr = np.array([r["sigma"] for r in R_tr]); q1, q2 = np.percentile(sig_tr, [33, 67])
regime = lambda t: "low vol" if t["sigma"] < q1 else ("high vol" if t["sigma"] > q2 else "mid vol")
P("| Strategy | low vol | mid vol | high vol | entry 10–14m | entry 5–9m | entry 1–4m |\n|---|---|---|---|---|---|---|")
for name, (s, *_r) in final.items():
    tr_ = B.run(W_te, s, B.Costs())
    rg = B.by_bucket(tr_, regime)
    tm = B.by_bucket(tr_, lambda t: "a" if t["entry_min"] >= 10 else ("b" if t["entry_min"] >= 5 else "c"))
    cell = lambda d, k: f"{d[k]['per_contract_c']:+.2f} ({d[k]['n']})" if k in d else "–"
    P(f"| {name} | {cell(rg, 'low vol')} | {cell(rg, 'mid vol')} | {cell(rg, 'high vol')} | {cell(tm, 'a')} | {cell(tm, 'b')} | {cell(tm, 'c')} |")
P("")

elapsed = round(time.time() - t0)
text = "\n".join(lines).replace("{elapsed}", str(elapsed))
os.makedirs(os.path.dirname(os.path.abspath(out_md)), exist_ok=True)
open(out_md, "w").write(text + "\n")
json.dump(out, open(os.path.join(os.path.dirname(__file__), "results_15m.json"), "w"), indent=1, default=str)
print(text)
